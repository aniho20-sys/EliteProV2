function Muscle({ name, selected, onToggle, paths }) {
  const active = selected.includes(name);
  return (
    <g
      className={`muscle-region${active ? ' active' : ''}`}
      onClick={() => onToggle(name)}
      role="button"
      aria-label={name}
      aria-pressed={active}
    >
      {paths.map((d, i) => (
        <path key={i} className="muscle-shape" d={d} />
      ))}
    </g>
  );
}

export default function MuscleSelector({ selected = [], onChange }) {
  const toggle = (name) => {
    onChange(selected.includes(name)
      ? selected.filter(m => m !== name)
      : [...selected, name]);
  };

  return (
    <div className="muscle-selector">
      <div className="muscle-bodies">

        {/* ── FRONT VIEW ── */}
        <div className="muscle-body-col">
          <span className="muscle-body-label">Front</span>
          <svg viewBox="0 0 35 93" className="muscle-svg">
            <g className="body-silhouette" aria-hidden="true">
              {FRONT_BODY.map((d, i) => <path key={i} d={d} />)}
            </g>
            {Object.entries(FRONT_MUSCLES).map(([name, paths]) => (
              <Muscle key={name} name={name} selected={selected} onToggle={toggle} paths={paths} />
            ))}
          </svg>
        </div>

        {/* ── BACK VIEW ── */}
        <div className="muscle-body-col">
          <span className="muscle-body-label">Back</span>
          <svg viewBox="37 0 35 93" className="muscle-svg">
            <g className="body-silhouette" aria-hidden="true">
              {BACK_BODY.map((d, i) => <path key={i} d={d} />)}
            </g>
            {Object.entries(BACK_MUSCLES).map(([name, paths]) => (
              <Muscle key={name} name={name} selected={selected} onToggle={toggle} paths={paths} />
            ))}
          </svg>
        </div>

      </div>

      {selected.length > 0 && (
        <div className="muscle-selected-chips">
          {selected.map(m => (
            <span key={m} className="muscle-chip">
              {m}
              <button
                type="button"
                className="muscle-chip-remove"
                onClick={() => toggle(m)}
                aria-label={`Remove ${m}`}
              >
                <X size={11} />
              </button>
            </span>
          ))}
        </div>
      )}
    </div>
  );
}
